export function EmojiPicker({
  open,
  onSelect,
  onClose,
}: {
  open: boolean
  onSelect: (emoji: string) => void
  onClose: () => void
}) {
  const [category, setCategory] = useState(0)
  const ref = useRef<HTMLDivElement>(null)

  useEffect(() => {
    if (!open) return
    function onClick(e: MouseEvent) {
      if (ref.current && !ref.current.contains(e.target as Node)) {
        onClose()
      }
    }
    function onKey(e: KeyboardEvent) {
      if (e.key === 'Escape') onClose()
    }
    document.addEventListener('mousedown', onClick)
    document.addEventListener('keydown', onKey)
    return () => {
      document.removeEventListener('mousedown', onClick)
      document.removeEventListener('keydown', onKey)
    }
  }, [open, onClose])

  if (!open) return null

  return (
    <div
      ref={ref}
      className="absolute bottom-14 left-2 z-40 w-80 h-72 bg-white dark:bg-[var(--wasl-sidebar-bg)] border border-border rounded-lg shadow-xl flex flex-col overflow-hidden"
    >
      <div className="flex-1 overflow-y-auto wasl-scroll p-2">
        <div className="text-xs font-medium text-muted-foreground px-1 pb-1">
          {EMOJI_CATEGORIES[category].name}
        </div>
        <div className="grid grid-cols-8 gap-0.5">
          {EMOJI_CATEGORIES[category].emojis.map((e, i) => (
            <button
              key={`${category}-${i}`}
              type="button"
              className="text-xl w-9 h-9 flex items-center justify-center rounded hover:bg-muted transition-colors"
              onClick={() => onSelect(e)}
            >
              {e}
            </button>
          ))}
        </div>
      </div>
      <div className="flex border-t border-border overflow-x-auto wasl-scroll">
        {EMOJI_CATEGORIES.map((c, i) => (
          <button
            key={c.name}
            type="button"
            onClick={() => setCategory(i)}
            className={`flex-1 min-w-0 py-2 px-1 text-base text-center hover:bg-muted transition-colors ${
              category === i ? 'bg-muted' : ''
            }`}
            title={c.name}
          >
            {c.emojis[0]}
          </button>
        ))}
      </div>
    </div>
  )
}
